"""Immutable training manifests derived through the same tracked tool DAG.

Revalidating a sample is data maintenance, not parameter unlearning or training.
"""
from __future__ import annotations

from copy import deepcopy
import hashlib
import json
from pathlib import Path

from .provenance import atomic_write_new_json, execution_binding
from .store import canonical


def _sample(ctx, args):
    observation = ctx.call("resolve", args["query"])
    if observation["status"] not in {"resolved", "conflict", "incomplete"}:
        raise ValueError("Cannot label an unsupported resolver status")
    if observation["status"] == "incomplete":
        target = {"action": "abstain", "arguments": {"reason": "incomplete_catalog"}}
    else:
        target = {"action": "answer", "arguments": {
            "status": observation["status"], "selection": observation["selection"],
            "citations": observation["citations"]}}
    # Targets are generated by a declared rule, never a free-running LLM.
    return {"id": args["id"], "query": args["query"], "observation": observation,
            "target": target, "label_rule": "finite-resolver-answer-v1"}


class TrainingLedger:
    def __init__(self, engine):
        if engine.mode == "positive":
            raise ValueError("Positive-row heuristics cannot certify training labels")
        self.engine = engine
        self.engine.register("training_sample", _sample, version="finite-resolver-answer-v1")
        self._samples = {}
        self._latest_revision = None
        self._latest_binding = None
        self._latest_content = {}

    def add(self, sample_id, query):
        if not isinstance(sample_id, str) or not sample_id:
            raise ValueError("sample_id must be nonempty")
        if sample_id in self._samples:
            raise ValueError("sample_id already exists; create a new identity")
        self._samples[sample_id] = json.loads(canonical(query))
        self._latest_revision = None
        self._latest_binding = None

    @property
    def needs_revalidation(self):
        return self._latest_binding != execution_binding(self.engine, self.engine.store.snapshot)

    def freeze(self, directory: Path, *, snapshot=None):
        if not self._samples:
            raise ValueError("Cannot freeze an empty dataset")
        snapshot = self.engine.store.snapshot if snapshot is None else snapshot
        binding = execution_binding(self.engine, snapshot)
        samples, changes = [], []
        for sample_id, query in sorted(self._samples.items()):
            if self.engine.registry_fingerprint != binding["registry_fingerprint"]:
                raise RuntimeError("Registered execution versions changed during dataset freeze")
            sample, receipt = self.engine.run_with_receipt(
                "training_sample", {"id": sample_id, "query": query}, snapshot=snapshot)
            if self.engine.registry_fingerprint != binding["registry_fingerprint"]:
                raise RuntimeError("Registered execution versions changed during dataset freeze")
            content = canonical(sample)
            samples.append({**sample, "snapshot_revision": snapshot.revision,
                            "content_sha256": hashlib.sha256(content.encode()).hexdigest(), "receipt": receipt})
            if self._latest_content.get(sample_id) != content:
                changes.append(sample_id)
        # A content-addressed immutable manifest binds labels and source evidence.
        # Real timing/audit metadata is intentionally not its semantic identity.
        semantic = {"snapshot_revision": snapshot.revision,
                    "snapshot_sha256": binding["snapshot_sha256"], "runtime_binding": binding,
                    "samples": [{k: v for k, v in row.items() if k != "receipt"} for row in samples]}
        digest = hashlib.sha256(canonical(semantic).encode()).hexdigest()
        manifest = {"schema_version": 1, "manifest_sha256": digest, **semantic,
                    "changed_sample_ids": changes,
                    "receipts": {row["id"]: row["receipt"] for row in samples},
                    "scope": "Frozen labels over a declared finite catalog; existing adapters are not modified or unlearned."}
        directory = Path(directory); directory.mkdir(parents=True, exist_ok=True)
        path = directory / f"dataset-r{snapshot.revision}-{digest[:16]}.json"
        atomic_write_new_json(path, manifest)
        self._latest_revision = snapshot.revision
        self._latest_binding = deepcopy(binding)
        self._latest_content = {row["id"]: canonical({k: v for k, v in row.items()
                            if k not in {"receipt", "snapshot_revision", "content_sha256"}}) for row in samples}
        return path, manifest


def route_failure(*, source_complete, snapshot_consistent, current_evidence, model_contract_passed):
    """A diagnostic decision table, not a learned optimal training scheduler."""
    if not snapshot_consistent:
        return "repair_publication"
    if not source_complete:
        return "collect_missing_evidence"
    if not current_evidence:
        return "refresh_tools"
    if not model_contract_passed:
        return "collect_behavior_errors_for_sft_review"
    return "no_parameter_update_needed"
